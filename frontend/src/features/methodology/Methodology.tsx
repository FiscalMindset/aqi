/**
 * Methodology.
 *
 * Every number on this page comes from `/v1/validation`, which is written only
 * by `model/evaluate.py`. Nothing here is a target, a round number, or a
 * placeholder: if the evaluation has not been run the page says so rather than
 * showing a plausible figure.
 *
 * The page is organised around the three questions a sceptic actually has:
 * how good is it, how do we know, and where does it break. The left-out
 * limitations are the most important part - an accuracy figure without its
 * failure modes is marketing.
 */

import { useTranslation } from "react-i18next";
import { useValidation } from "../../hooks/useApi";

function fmt(v: number | undefined, digits = 1): string {
  return typeof v === "number" && Number.isFinite(v) ? v.toFixed(digits) : "—";
}

function Row({
  label,
  value,
  testId,
  note,
}: {
  label: string;
  value: string;
  testId?: string;
  note?: string;
}) {
  return (
    <tr>
      <td className="py-1.5 pr-3 text-slate-300">{label}</td>
      <td className="py-1.5 text-right font-mono" data-testid={testId}>
        {value}
      </td>
      {note && <td className="py-1.5 pl-3 text-xs text-slate-500">{note}</td>}
    </tr>
  );
}

export function Methodology() {
  const { t } = useTranslation();
  const { data, isLoading, error } = useValidation();

  if (isLoading) return <div className="p-8 text-slate-400">Loading metrics…</div>;
  if (error || !data) {
    return (
      <div className="p-8" role="alert">
        <p className="text-rose-300">The evaluation metrics could not be read.</p>
        <p className="mt-1 text-sm text-slate-400">
          They are generated by running the evaluation script; until then this
          page stays empty rather than showing an estimate of its accuracy.
        </p>
      </div>
    );
  }

  const th = data.temporal_holdout ?? {};
  const loso = data.loso_mean ?? {};
  const baselines = data.baselines ?? {};
  const persistence = baselines["persistence-lag1h"];
  const winner = data.winner;
  // The model is only worth using if it beats "same value an hour ago".
  const beatsPersistence =
    typeof persistence?.mae === "number" && typeof th.mae === "number"
      ? th.mae < persistence.mae
      : null;

  return (
    <div className="mx-auto max-w-4xl space-y-6 p-4" data-testid="methodology">
      <header>
        <h1 className="text-xl font-bold">{t("methodology.title")}</h1>
        <p className="mt-1 text-sm text-slate-400">
          Every figure below is read from the metrics file written by the
          evaluation run. Run <code className="font-mono">{data.version}</code>{" "}
          built {String(data.created_utc).replace("T", " ").slice(0, 19)} over{" "}
          {Number(data.n_rows).toLocaleString()} labelled hourly observations.
        </p>
      </header>

      <section className="rounded-xl border border-white/10 bg-slate-900/40 p-4">
        <h2 className="mb-2 text-sm font-semibold uppercase tracking-wide text-slate-400">
          {t("methodology.holdout")} — predicting the next hour
        </h2>
        <table className="w-full text-sm">
          <tbody>
            <Row label="Mean absolute error (MAE)" value={fmt(th.mae)} testId="val-mae"
              note="average size of the mistake" />
            <Row label="Root mean squared error" value={fmt(th.rmse)}
              note="punishes large misses harder" />
            <Row label="R²" value={fmt(th.r2, 3)}
              note="share of variance explained; 1 is perfect" />
            <Row label="Bias" value={fmt(th.bias)}
              note="0 means no systematic over- or under-prediction" />
          </tbody>
        </table>
        <p className="mt-2 text-xs text-slate-400">{data.interval_coverage_note}</p>
      </section>

      <section className="rounded-xl border border-white/10 bg-slate-900/40 p-4">
        <h2 className="mb-1 text-sm font-semibold uppercase tracking-wide text-slate-400">
          The number that matters most
        </h2>
        <p className="mb-2 text-sm text-slate-400">
          The figures above test the model at stations it trained on. This one
          holds each monitoring station out of training entirely and predicts it
          from the others — which is the situation you are actually in, standing
          on a street with no monitor.
        </p>
        <table className="w-full text-sm">
          <tbody>
            <Row label="Unseen-station MAE" value={fmt(loso.mae)} testId="val-loso-mae"
              note="leave-one-station-out" />
            <Row label="Unseen-station RMSE" value={fmt(loso.rmse)} />
            <Row label="Unseen-station R²" value={fmt(loso.r2, 3)} />
            <Row label="Unseen-station bias" value={fmt(loso.bias)} />
          </tbody>
        </table>
        <p className="mt-2 text-xs text-slate-400">
          Trained on {Number(loso.n_train ?? 0).toLocaleString()} observations
          across stations, evaluated on{" "}
          {Number(loso.n_test ?? 0).toLocaleString()} from the held-out station.
        </p>
      </section>

      <section className="rounded-xl border border-white/10 bg-slate-900/40 p-4">
        <h2 className="mb-2 text-sm font-semibold uppercase tracking-wide text-slate-400">
          Compared against doing nothing clever
        </h2>
        <p className="mb-2 text-sm text-slate-400">
          A model that cannot beat &ldquo;assume it is the same as an hour
          ago&rdquo; is not worth running. Here is every baseline on the same
          split.
        </p>
        <table className="w-full text-sm">
          <thead>
            <tr className="border-b border-white/10 text-left text-slate-400">
              <th className="pb-1.5">Approach</th>
              <th className="pb-1.5 text-right">MAE</th>
              <th className="pb-1.5 text-right">R²</th>
            </tr>
          </thead>
          <tbody>
            {Object.entries(baselines).map(([name, b]) => (
              <tr key={name} className="border-b border-white/5">
                <td className="py-1.5">{name.replace(/-/g, " ")}</td>
                <td className="py-1.5 text-right font-mono">{fmt(b?.mae)}</td>
                <td className="py-1.5 text-right font-mono">{fmt(b?.r2, 3)}</td>
              </tr>
            ))}
            <tr className="border-t border-white/20">
              <td className="py-1.5 font-semibold" data-testid="winner">{winner}</td>
              <td className="py-1.5 text-right font-mono font-semibold">{fmt(th.mae)}</td>
              <td className="py-1.5 text-right font-mono font-semibold">{fmt(th.r2, 3)}</td>
            </tr>
          </tbody>
        </table>
        {beatsPersistence === true && (
          <p className="mt-2 text-xs text-emerald-300">
            The shipped model beats persistence by{" "}
            {fmt((persistence?.mae ?? 0) - (th.mae ?? 0))} µg/m³ on average.
          </p>
        )}
        {beatsPersistence === false && (
          <p className="mt-2 text-xs text-amber-300">
            Persistence is at least as good as the model on this split, so the
            API serves the station reading unchanged rather than pretending the
            model helps.
          </p>
        )}
      </section>

      <section className="rounded-xl border border-amber-500/30 bg-amber-500/5 p-4">
        <h2 className="mb-2 text-sm font-semibold uppercase tracking-wide text-amber-300">
          Where this does not work
        </h2>
        <ul className="list-disc space-y-1.5 pl-5 text-sm text-slate-300">
          <li>
            CPCB categories are defined on <strong>24-hour averages</strong>. We
            apply them to an hourly value, which is deliberately conservative: a
            single bad hour reads worse than the day as a whole.
          </li>
          <li>
            The estimate is only as fresh as the nearest official station. When
            that reading is hours old, so is the estimate, and the interface
            says so on every card.
          </li>
          <li>
            Attribution names source <em>categories</em> and mapped OSM sites
            that are <strong>upwind</strong>. It does not measure emissions, and
            a source being upwind is an association, not a proven cause.
          </li>
          <li>
            Inside the New York refinery fire plume the model is untested and
            should not be trusted.
          </li>
          <li>
            Weather feeds and satellite fire detection degrade gracefully: when
            they are missing the explanation omits what depended on them instead
            of filling the gap.
          </li>
        </ul>
      </section>

      <section className="rounded-xl border border-white/10 bg-slate-900/40 p-4">
        <h2 className="mb-2 text-sm font-semibold uppercase tracking-wide text-slate-400">
          How the number is produced
        </h2>
        <ol className="list-decimal space-y-1.5 pl-5 text-sm text-slate-300">
          <li>
            Find the nearest official station and take its reading from about an
            hour ago.
          </li>
          <li>
            Predict the next hour with a gradient-boosted tree model on that
            anchor, using weather, time of day and nearby sources.
          </li>
          <li>
            Calibrate an 80% interval from held-out residuals, so the range widens
            where the model is genuinely less certain.
          </li>
          <li>
            If the model cannot be used at that point, serve the station reading
            unchanged and label it as such.
          </li>
        </ol>
        <p className="mt-2 text-xs text-slate-400">
          Metrics on this page are regenerated only by{" "}
          <code className="font-mono">model/evaluate.py</code> and are never
          edited by hand.
        </p>
      </section>
    </div>
  );
}

export default Methodology;