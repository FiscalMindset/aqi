"""Model tests: leakage prevention, interval coverage, baseline regression.

These enforce the honesty rules:
  1. No feature may see the target hour's reading or the target station's own
     current value (leakage test builds a controlled snapshot).
  2. Interval coverage must match the target on the holdout (the metrics file
     is regenerated by evaluation; this test compares against it, never against
     numbers typed into the test).
  3. The persisted metrics must beat or match baselines within the documented
     decision rule; if not, the winner field must say so.
"""

from __future__ import annotations

import json
from datetime import datetime, timedelta
from typing import Any

import numpy as np
import pytest

from dhuan.model.features import (
    FEATURE_NAMES,
    build_training_frame,
    calendar_features,
    lag_features,
    load_snapshot,
    snapshot_hash,
    static_features,
    weather_features,
)
from dhuan.model.train import ARTIFACTS, DATA, conformal_radius

METRICS_PATH = ARTIFACTS / "metrics.json"
SNAPSHOT_PATH = DATA / "training_snapshot.json"


@pytest.fixture(scope="module")
def metrics() -> dict[str, Any]:
    if not METRICS_PATH.exists():
        pytest.skip("no metrics.json; run `make train` first")
    return json.loads(METRICS_PATH.read_text())


def test_feature_names_are_stable() -> None:
    assert len(FEATURE_NAMES) == len(set(FEATURE_NAMES))
    assert "value" not in FEATURE_NAMES
    assert "target" not in FEATURE_NAMES


def test_calendar_and_weather_features_are_pure() -> None:
    ts = datetime(2024, 3, 10, 14, 30)
    feats = calendar_features(ts)
    assert feats["hour"] == 14.0
    w = weather_features(
        {"wind_speed": 3.0, "wind_gust": 5.0, "temp_c": 25.0, "rh": 40.0,
         "precip": 0.0, "wind_dir": 270.0}
    )
    assert abs(w["wind_dir_sin"] - np.sin(np.radians(270.0))) < 1e-9
    assert w["wind_speed"] == 3.0


def test_lag_features_use_only_strictly_past_values() -> None:
    base = datetime(2024, 1, 10, 12, 0)
    history = {base: 999.0, base - timedelta(hours=1): 100.0, base - timedelta(hours=24): 110.0}
    lag1, lag24, roll6, _found = lag_features(history, base)
    assert lag1 == 100.0  # the target hour's own 999 must NOT appear
    assert lag24 == 110.0
    roll6_history = {base - timedelta(hours=h): float(h) for h in range(2, 8)}
    _l1, _l24, roll6, _f = lag_features(roll6_history, base)
    assert roll6 == sum(h for h in range(2, 8)) / 6


def test_leakage_features_ignore_target_hour_reading() -> None:
    """Build a two-hour snapshot; features for hour 2 must not contain hour 2's value."""
    snapshot = {
        "stations": [
            {
                "location_id": 1,
                "sensor_id": 1,
                "location": "Test",
                "lat": 28.6,
                "lon": 77.2,
                "datetime": "2024-01-10T10:00:00",
                "value": 111.0,
            },
            {
                "location_id": 1,
                "sensor_id": 1,
                "location": "Test",
                "lat": 28.6,
                "lon": 77.2,
                "datetime": "2024-01-10T11:00:00",
                "value": 222.0,
            },
        ],
        "weather": [
            {"lat": 28.6, "lon": 77.2, "time": "2024-01-10T10:00", "wind_speed": 2.0,
             "wind_gust": 3.0, "temp_c": 20.0, "rh": 50.0, "precip": 0.0, "wind_dir": 90.0},
            {"lat": 28.6, "lon": 77.2, "time": "2024-01-10T11:00", "wind_speed": 2.5,
             "wind_gust": 3.5, "temp_c": 21.0, "rh": 51.0, "precip": 0.0, "wind_dir": 95.0},
        ],
    }
    rows, labels, _meta = build_training_frame(snapshot)
    assert len(rows) == 2
    # second row: lag1 must be the FIRST hour's value (111), never 222
    assert rows[1]["station_lag1"] == 111.0
    assert labels[1] == 222.0


def test_training_features_never_contain_water_reading() -> None:
    """No feature name or value stream references pm25 readings of the target."""
    snapshot = load_snapshot()
    rows, _labels, _meta = build_training_frame(snapshot)
    names = set(rows[0])
    for banned in ("value", "pm25", "reading", "target", "label"):
        assert not any(banned in n.lower() for n in names)


def test_static_features_bounded() -> None:
    feats = static_features(
        dhuan_point(), []
    )
    for key, value in feats.items():
        assert value >= 0.0
        assert value <= 99.0 if "dist" in key else value >= 0


def dhuan_point():
    from dhuan.core.units import Point

    return Point(lat=28.6139, lon=77.2090)


def test_snapshot_hash_is_recorded(metrics: dict[str, Any]) -> None:
    if not SNAPSHOT_PATH.exists():
        pytest.skip("no snapshot")
    snapshot = load_snapshot()
    assert metrics["snapshot_sha256"] == snapshot_hash(snapshot)


def test_temporal_holdout_metrics_are_real(metrics: dict[str, Any]) -> None:
    t = metrics["temporal_holdout"]
    assert t["n_test"] > 100
    assert t["mae"] > 0
    assert t["rmse"] >= t["mae"]
    assert -1.0 <= t["r2"] <= 1.0


def test_interval_coverage_close_to_target(metrics: dict[str, Any]) -> None:
    """Conformal interval must cover ~80% of the holdout."""
    notes = metrics.get("notes", [])
    cov_note = [n for n in notes if "empirical coverage" in n]
    assert cov_note, "conformal calibration must be recorded"
    # extract the empirical coverage number
    import re

    m = re.search(r"coverage: (\d\.\d+)", cov_note[0])
    if m:
        cov = float(m.group(1))
        assert 0.75 <= cov <= 0.85


def test_winner_is_declared_honestly(metrics: dict[str, Any]) -> None:
    t = metrics["temporal_holdout"]
    baselines = metrics["baselines"]
    best = min(baselines.values(), key=lambda b: b["mae"])
    if t["mae"] <= best["mae"]:
        assert metrics["winner"].startswith("quantile-model")
    else:
        assert metrics["winner"].startswith("nearest-station-baseline")
        # the model is not meaningfully better: the UI must say so, and the
        # card must present both numbers (checked in test_model_card.py)


def test_loso_stats_present(metrics: dict[str, Any]) -> None:
    assert len(metrics["loso_stations"]) >= 2
    for row in metrics["loso_stations"]:
        assert row["n_test"] > 50
        assert row["mae"] > 0
    assert metrics["loso_mean"]["mae"] > 0


def test_conformal_radius_function() -> None:
    # residuals from 0..9: the 0.8 quantile is 8
    y = np.asarray([10.0 + float(r) for r in range(10)] * 10)
    mid = np.asarray([10.0] * 100)
    r = conformal_radius(y, mid, coverage=0.8)
    assert 7.0 <= r <= 8.5  # numpy linear-interpolation quantile of 0..9


def test_metrics_json_written_by_evaluate(metrics: dict[str, Any]) -> None:
    assert metrics["version"].startswith("eval")
    assert metrics["n_rows"] > 1000
    assert len(metrics["features"]) == len(FEATURE_NAMES)
