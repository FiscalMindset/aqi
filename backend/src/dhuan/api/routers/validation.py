"""GET /v1/validation — the real, generated evaluation metrics (no re-computing)."""

from __future__ import annotations

import json
from pathlib import Path

from fastapi import APIRouter

from dhuan.api.errors import Problem, ProblemType
from dhuan.api.models import ValidationOut

router = APIRouter(prefix="/v1", tags=["validation"])

METRICS = Path(__file__).resolve().parents[4] / "models" / "metrics.json"


@router.get(
    "/validation",
    response_model=ValidationOut,
    summary="Latest evaluation metrics generated by model/evaluate.py",
    response_description="Temporal holdout, LOSO, baselines and the shipped winner.",
)
async def validation() -> ValidationOut:
    if not METRICS.exists():
        raise Problem(
            problem_type=ProblemType.NOT_FOUND,
            title="No evaluation metrics",
            status=404,
            detail="Run `make train` to generate metrics.json.",
        )
    metrics = json.loads(METRICS.read_text())
    coverage_note = "conformal 80% (see notes in metrics.json)"
    for note in metrics.get("notes", []):
        if "coverage" in note:
            coverage_note = note
            break
    return ValidationOut(
        version=metrics["version"],
        created_utc=metrics["created_utc"],
        n_rows=metrics["n_rows"],
        temporal_holdout=metrics["temporal_holdout"],
        loso_mean=metrics["loso_mean"],
        baselines=metrics["baselines"],
        winner=metrics["winner"],
        interval_coverage_note=coverage_note,
    )
