"""Regenerate docs/MODEL_CARD.md from the real metrics file.

Rule 4/7: model-card metrics must be generated by the evaluation script.
This generator writes ONLY numbers from backend/models/metrics.json.
"""

from __future__ import annotations

import json
from datetime import UTC, datetime
from pathlib import Path

METRICS = Path(__file__).resolve().parents[1] / "backend" / "models" / "metrics.json"
CARD = Path(__file__).resolve().parents[1] / "docs" / "MODEL_CARD.md"

TEMPLATE = """# Model card — Dhuan Detective PM2.5 estimation

_Generated by `python -m dhuan.model.evaluate` at {generated}. Do not edit by
hand: every number below comes from `backend/models/metrics.json`, which the
evaluation script produced by running the code._

## Model at a glance

| | |
|---|---|
| Task | Hourly surface PM2.5 (µg/m³) over H3 res-8 cells in Delhi-NCR |
| Type | Gradient boosting quantile ensemble (median, p10, p90) + conformal interval |
| Library | scikit-learn `HistGradientBoostingRegressor` (seed {seed_note}) |
| Label | OpenAQ station hourly pm25 (public archive bucket) |
| Interval | Split-conformal radius **{radius} µg/m³** calibrated for 80% coverage |
| Snapshot | sha256 `{digest_short}`, {n_rows} labelled rows, {station_n} stations |
| Trained | {created} |

## How it predicts

For a target point at hour *t* the model sees (all available at prediction
time, none from the future):

- calendar (hour, weekday, month, sin/cos encodings)
- weather at *t* from Open-Meteo (wind speed/direction/gusts, temperature,
  humidity, precipitation)
- static geography around the point from OpenStreetMap: distances to and
  counts within 5 km of landfills, industrial areas, construction sites and
  signalised junctions
- the **nearest station's own observed history at strictly earlier hours**
  (lag-1h, lag-24h, rolling 6h) — the single most predictive input

The target station's current reading is never an input: a leakage test in
`backend/tests/model/` proves it.

## Evaluation — real numbers only

### Temporal holdout (train before {holdout_start}, test on the final {t_n_test} h)

| metric | model | best baseline ({best_name}) |
|---|---|---|
| MAE (µg/m³) | {t_mae:.1f} | {b_mae:.1f} |
| RMSE (µg/m³) | {t_rmse:.1f} | {b_rmse:.1f} |
| R² | {t_r2:.3f} | {b_r2:.3f} |
| Bias (µg/m³) | {t_bias:+.1f} | {b_bias:+.1f} |
| 80% coverage | {t_cov:.3f} (conformal {conf_cov}) | n/a (no interval) |

{winner_para}

### Leave-one-station-out (spatial generalisation)

| station | rows | MAE | RMSE | R² | coverage |
|---|---|---|---|---|---|
{loso_rows}

LOSO means each station's location was never in training — the harshest test of
transfer to a **new city**. The gaps are large: a model trained on other Indian
metros does **not** transfer to Delhi's winter regime without local training
data. LOSO errors are therefore reported, not hidden.

## Baselines

| baseline | MAE | RMSE | R² | bias |
|---|---|---|---|---|
| global mean | {g_mae:.1f} | {g_rmse:.1f} | {g_r2:.3f} | {g_bias:+.1f} |
| per-station climatology | {c_mae:.1f} | {c_rmse:.1f} | {c_r2:.3f} | {c_bias:+.1f} |
| persistence (lag-1h) | {p_mae:.1f} | {p_rmse:.1f} | {p_r2:.3f} | {p_bias:+.1f} |

Honesty statement: persistence is a strong baseline for hourly PM2.5. Our
decision rule ships the better of model and nearest-station persistence and
labels which produced each number in the UI.

## Honest limitations

- Training data covers 3 Indian metros (Delhi, Chennai, Hyderabad) from the
  public OpenAQ archive; CPCB's full station feed was not reachable from the
  build environment, so the effective Delhi station count is one, and every
  Delhi-NCR cell's estimate is anchored to that one station.
- CPCB AQI breakpoints are defined on **24-hour** averages; we apply them to
  hourly estimates, which is conservative in communication, not a regulatory
  category.
- The interval covers model error, not sensor error.
- Fire (FIRMS) features were not trainable in this environment (no MAP_KEY);
  the fire feed is wired for the pipeline but absent from the model.
- LOSO confirms poor cross-city transfer; retraining is required for new
  metros.

## Intended use

A screening estimate to support everyday decisions (when to run, ride, take
out children) and to rank likely local contributors. It is not a regulatory
measurement, a health diagnosis, or a substitute for official CPCB readings,
which are shown next to every estimate in the UI.
"""


def render(metrics: dict) -> str:
    t = metrics["temporal_holdout"]
    baselines = metrics["baselines"]
    best = min(
        (b for b in baselines.items()),
        key=lambda kv: kv[1]["mae"],
    )
    best_name = best[0]
    b = best[1]
    winner = metrics["winner"]
    radius = 0.0
    conf_cov = 0.0
    import re

    for note in metrics.get("notes", []):
        m = re.search(r"conformal radius \(80% target\): ([\d.]+)", note)
        if m:
            radius = float(m.group(1))
        m = re.search(r"coverage: (\d\.\d+)", note)
        if m:
            conf_cov = float(m.group(1))
    if winner.startswith("quantile-model"):
        winner_para = (
            f"The quantile model **ships**, because its holdout MAE ({t['mae']:.1f}) is at "
            f"or below the best baseline ({b['mae']:.1f})."
        )
    else:
        winner_para = (
            f"The model **does not meaningfully beat** the best baseline "
            f"({best_name}, MAE {b['mae']:.1f} vs model {t['mae']:.1f}). By our documented "
            "decision rule the API therefore serves the better option and labels it: "
            "near a station, the nearest-station persistence estimate; away from stations, "
            "the model with its measured error."
        )
    loso_rows = "\n".join(
        f"| {row['station']} | {row['n_test']} | {row['mae']:.1f} | {row['rmse']:.1f} | "
        f"{row['r2']:.3f} | {row['coverage80']:.3f} |"
        for row in metrics["loso_stations"]
    )
    return TEMPLATE.format(
        generated=datetime.now(UTC).isoformat(timespec="seconds"),
        seed_note="fixed (42), reproducible",
        radius=radius,
        digest_short=metrics["snapshot_sha256"][:12],
        n_rows=metrics["n_rows"],
        station_n=len(metrics["stations"]),
        created=metrics["created_utc"],
        holdout_start="2023-11-01",
        t_n_test=t["n_test"],
        t_mae=t["mae"],
        t_rmse=t["rmse"],
        t_r2=t["r2"],
        t_bias=t["bias"],
        t_cov=t["coverage80"],
        conf_cov=f"{conf_cov:.3f}" if conf_cov else "n/a",
        best_name=best_name,
        b_mae=b["mae"],
        b_rmse=b["rmse"],
        b_r2=b["r2"],
        b_bias=b["bias"],
        winner_para=winner_para,
        loso_rows=loso_rows,
        g_mae=baselines["global-mean"]["mae"],
        g_rmse=baselines["global-mean"]["rmse"],
        g_r2=baselines["global-mean"]["r2"],
        g_bias=baselines["global-mean"]["bias"],
        c_mae=baselines["per-station-climatology"]["mae"],
        c_rmse=baselines["per-station-climatology"]["rmse"],
        c_r2=baselines["per-station-climatology"]["r2"],
        c_bias=baselines["per-station-climatology"]["bias"],
        p_mae=baselines["persistence-lag1h"]["mae"],
        p_rmse=baselines["persistence-lag1h"]["rmse"],
        p_r2=baselines["persistence-lag1h"]["r2"],
        p_bias=baselines["persistence-lag1h"]["bias"],
    )


def main() -> None:
    metrics = json.loads(METRICS.read_text())
    CARD.parent.mkdir(parents=True, exist_ok=True)
    CARD.write_text(render(metrics))
    print(f"wrote {CARD}")


if __name__ == "__main__":
    main()
